export const out = (
  weight: number,
  text: string,
  effect: Effect = {},
  minRep?: number,
): OutcomeDefinition => ({
  weight,
  text,
  effect,
  ...(minRep === undefined ? {} : { minRep }),
});
export const option = (
  id: string,
  label: string,
  hint: string,
  cost: EventChoice['cost'],
  outcomes: OutcomeDefinition[],
): EventChoice => ({ id, label, hint, cost, outcomes });
